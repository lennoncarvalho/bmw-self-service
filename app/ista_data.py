"""ECU job files and model ECU lists from a 4.29 data bundle or a user folder (D-62).

Two providers, consulted in order:

1. The compact bundle under ``ista_bundle/`` produced by ``scripts/build_ista_bundle.py``
   (job files plus per-series ECU lists and a manifest with SHA-256 provenance).
2. A user-selected ISTA 4.29 folder (``Rheingold/Ecu`` job files, ``PSdZ/kiswb`` ECU
   lists, ``PSdZ/mapping/brref.xml`` series map), stored in QSettings ``ista/folder``.

Every file read here is untrusted data. The KIS ECU list is an HSQLDB 2.5.x cached
table, read directly and read-only (no database engine, nothing written); the group
assignment table comes from ``t_grtb.prg``. Formats are documented in
``tasks/ista-job-engine-plan.md`` (M2).
"""

import json
import logging
import re
import sqlite3
import struct
import xml.etree.ElementTree as ET
from collections.abc import Iterable
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Protocol, TypedDict

from app.resources import resource_path

logger = logging.getLogger(__name__)

SETTINGS_KEY = "ista/folder"
BUNDLE_DIRNAME = "ista_bundle"
BUNDLE_FORMAT = 1
JOB_SUFFIXES = (".prg", ".grp")
GROUP_TABLE_FILE = "t_grtb"
GROUP_TABLE = "ZUORDNUNGSTABELLEUDS"
SUPPORTED_VERSION_PREFIX = "4.29"

# KIS.BORDNETZTEILNEHMER as created in every 4.29 kiswb database; rows are parsed
# against exactly this column list and refused if the definition differs.
_KIS_TABLE = "KIS.BORDNETZTEILNEHMER"
_KIS_CREATE = (
    "CREATE CACHED TABLE KIS.BORDNETZTEILNEHMER(ID INTEGER GENERATED BY DEFAULT AS "
    "IDENTITY(START WITH 1) NOT NULL,NAME VARCHAR(26) NOT NULL,DIAGNOSEADRESSE INTEGER "
    "NOT NULL,BESCHREIBUNG VARCHAR(1024),HAS_GWT CHARACTER(1),CONSTRAINT "
    "PK_BORDNETZTEILNEHMER PRIMARY KEY(ID))"
)
_KIS_COLUMNS = "isisc"  # INTEGER, VARCHAR, INTEGER, VARCHAR, CHARACTER
_KIS_NODE_SIZE = 16  # AVL node per index: balance, left, right, parent (int32 BE)
_KIS_MAX_ROW = 0x10000
_KIS_MAX_ROWS = 100_000

_XOR = bytes(b ^ 0xF7 for b in range(256))  # job file body obfuscation
_PRG_TABLE_DIRECTORY = 0x84
_PRG_MAX_TABLES = 20_000
_PRG_MAX_CELL = 1024
_SERIES_PATTERN = re.compile(r"^[A-Z0-9]{3,5}$")


class DataFormatError(ValueError):
    """A data file does not have the expected structure."""


class IstaEcu(TypedDict):
    """One ECU of a model's target ECU list (KIS ``BORDNETZTEILNEHMER``)."""

    name: str
    address: int
    description: str
    gateway: bool
    groups: list[str]


@dataclass(frozen=True)
class GroupAssignment:
    """One ``t_grtb`` row: a diagnostic address and SGBD index map to a variant."""

    address: int
    sgbd_index: str
    variant: str
    group: str


@dataclass(frozen=True)
class FolderCheck:
    """Validation result of a user-selected ISTA folder."""

    ok: bool
    message: str
    root: Path | None = None
    version: str = ""
    prg_count: int = 0
    grp_count: int = 0
    kis_series: list[str] = field(default_factory=list)

    @property
    def version_supported(self) -> bool:
        """Whether the recorded data version is the targeted 4.29 release."""
        return self.version.startswith(SUPPORTED_VERSION_PREFIX)


# ---------------------------------------------------------------------------
# Job file tables


def read_job_table(path: Path, table: str) -> tuple[list[str], list[list[str]]]:
    """Read one table of a PRG/GRP job file.

    Args:
        path: Job file.
        table: Table name, matched case-insensitively.

    Returns:
        ``(columns, rows)``; every row has one cell per column.

    Raises:
        DataFormatError: The file or table structure is invalid or the table is absent.
        OSError: The file cannot be read.
    """
    raw = path.read_bytes()
    directory = _int32_le(raw, _PRG_TABLE_DIRECTORY)
    count = _int32_le(_decode(raw, directory, 4), 0)
    if not 0 <= count <= _PRG_MAX_TABLES:
        raise DataFormatError(f"{path.name}: implausible table count")
    wanted = table.upper()
    for index in range(count):
        entry = _decode(raw, directory + 4 + index * 0x50, 0x50)
        name = entry[:0x40].split(b"\0", 1)[0].decode("cp1252", errors="replace")
        if name.upper() != wanted:
            continue
        offset, columns, rows = (_int32_le(entry, at) for at in (0x40, 0x48, 0x4C))
        if columns <= 0 or rows < 0 or columns * (rows + 1) > len(raw) - offset:
            raise DataFormatError(f"{path.name}: table {name} is truncated")
        cells: list[str] = []
        position = offset
        for _ in range(columns * (rows + 1)):
            end = raw.find(b"\xf7", position, position + _PRG_MAX_CELL + 1)  # NUL ^ 0xF7
            if end < 0:
                raise DataFormatError(f"{path.name}: table {name} has an unterminated cell")
            cells.append(raw[position:end].translate(_XOR).decode("cp1252", errors="replace"))
            position = end + 1
        header = cells[:columns]
        body = [cells[columns * (r + 1) : columns * (r + 2)] for r in range(rows)]
        return header, body
    raise DataFormatError(f"{path.name}: table {table} not found")


def read_group_assignments(group_table_file: Path) -> list[GroupAssignment]:
    """Parse the UDS group assignment table (address + SGBD index -> variant, group).

    Rows with a wildcard address or no variant are skipped.
    """
    columns, rows = read_job_table(group_table_file, GROUP_TABLE)
    try:
        key, variant, group = (columns.index(c) for c in ("ADR_INDEX", "SGBD", "GRUPPE"))
    except ValueError as exc:
        raise DataFormatError(f"{GROUP_TABLE} has unexpected columns") from exc
    result: list[GroupAssignment] = []
    for row in rows:
        address_text, _, index_text = row[key].partition(" ")
        if not row[variant] or not row[group]:
            continue
        try:
            address = int(address_text, 16)
        except ValueError:
            continue  # wildcard terminator row ("?? ??????")
        result.append(
            GroupAssignment(address, index_text, row[variant].lower(), row[group].lower())
        )
    return result


def groups_by_address(assignments: Iterable[GroupAssignment]) -> dict[int, list[str]]:
    """Group files serving each diagnostic address, sorted."""
    mapping: dict[int, set[str]] = {}
    for row in assignments:
        mapping.setdefault(row.address, set()).add(row.group)
    return {address: sorted(groups) for address, groups in mapping.items()}


def _decode(raw: bytes, offset: int, length: int) -> bytes:
    if offset < 0 or offset + length > len(raw):
        raise DataFormatError("Job file offset is outside the file")
    return raw[offset : offset + length].translate(_XOR)


def _int32_le(data: bytes, offset: int) -> int:
    if offset < 0 or offset + 4 > len(data):
        raise DataFormatError("Job file offset is outside the file")
    return int(struct.unpack_from("<i", data, offset)[0])


# ---------------------------------------------------------------------------
# KIS (HSQLDB 2.5.x cached table) reader


def read_kis_ecus(kis_dir: Path, groups: dict[int, list[str]] | None = None) -> list[IstaEcu]:
    """Read a model's target ECU list from ``kiswb/<main series>``.

    The table definition, data file scale and the primary-key AVL root plus row count
    come from ``KIS.script``; rows are read from ``KIS.data`` by walking that index.

    Args:
        kis_dir: ``PSdZ/kiswb/<main series>`` directory.
        groups: Optional group files per address, added to each ECU.

    Returns:
        ECUs sorted by address and name.

    Raises:
        DataFormatError: Unexpected definition, row layout or row count.
        OSError: The files cannot be read.
    """
    properties = (kis_dir / "KIS.properties").read_text(encoding="latin-1")
    if not re.search(r"^version=2\.5\.[01]$", properties, re.MULTILINE):
        raise DataFormatError("KIS database version is not 2.5.0/2.5.1")
    script = (kis_dir / "KIS.script").read_text(encoding="utf-8", errors="replace")
    if _KIS_CREATE not in script.splitlines():
        raise DataFormatError("KIS ECU table definition differs from the supported one")
    scale_match = re.search(r"^SET FILES SCALE (\d+)$", script, re.MULTILINE)
    index_match = re.search(
        rf"^SET TABLE {re.escape(_KIS_TABLE)} INDEX '([\d ]+)'$", script, re.MULTILINE
    )
    if scale_match is None or index_match is None:
        raise DataFormatError("KIS ECU table index or file scale is missing")
    scale = int(scale_match.group(1))
    numbers = [int(n) for n in index_match.group(1).split()]
    if len(numbers) != 3 or scale <= 0:
        raise DataFormatError("KIS ECU table index has an unexpected form")
    root, expected = numbers[0], numbers[-1]
    if not 0 <= expected <= _KIS_MAX_ROWS:
        raise DataFormatError("KIS ECU table row count is implausible")
    ecus: list[IstaEcu] = []
    if expected == 0:
        return ecus
    data_file = kis_dir / "KIS.data"
    size = data_file.stat().st_size
    seen: set[int] = set()
    pending = [root]
    with data_file.open("rb") as handle:
        while pending:
            position = pending.pop()
            if position in seen or len(seen) >= expected:
                raise DataFormatError("KIS ECU table index is inconsistent")
            seen.add(position)
            row, left, right = _kis_row(handle, position * scale, size)
            ecus.append(_kis_ecu(row, groups))
            pending.extend(p for p in (left, right) if p > 0)
    if len(ecus) != expected:
        raise DataFormatError("KIS ECU table row count does not match its index")
    ecus.sort(key=lambda e: (e["address"], e["name"]))
    return ecus


def _kis_row(handle: Any, offset: int, size: int) -> tuple[list[Any], int, int]:
    if offset < 0 or offset + 4 > size:
        raise DataFormatError("KIS row position is outside the data file")
    handle.seek(offset)
    head = handle.read(4)
    length = int.from_bytes(head, "big", signed=True)
    if not 4 + _KIS_NODE_SIZE < length <= _KIS_MAX_ROW or offset + length > size:
        raise DataFormatError("KIS row has an implausible size")
    data = head + handle.read(length - 4)
    _balance, left, right, _parent = struct.unpack_from(">iiii", data, 4)
    position = 4 + _KIS_NODE_SIZE
    values: list[Any] = []
    for kind in _KIS_COLUMNS:
        if position >= len(data):
            raise DataFormatError("KIS row is truncated")
        present, position = data[position], position + 1
        if present == 0:
            values.append(None)
            continue
        if present != 1 or position + 4 > len(data):
            raise DataFormatError("KIS row has an invalid column marker")
        number = int.from_bytes(data[position : position + 4], "big", signed=True)
        position += 4
        if kind == "i":
            values.append(number)
            continue
        if number < 0 or position + number > len(data):
            raise DataFormatError("KIS row string exceeds the row")
        # Java modified UTF-8; identical to UTF-8 for these texts.
        values.append(data[position : position + number].decode("utf-8", errors="replace"))
        position += number
    return values, left, right


def _kis_ecu(row: list[Any], groups: dict[int, list[str]] | None) -> IstaEcu:
    _id, name, address, description, gateway = row
    if not isinstance(name, str) or not isinstance(address, int) or not 0 <= address <= 0xFF:
        raise DataFormatError("KIS ECU row has an invalid name or address")
    return IstaEcu(
        name=name,
        address=address,
        description=description or "",
        gateway=gateway == "Y",
        groups=list((groups or {}).get(address, [])),
    )


