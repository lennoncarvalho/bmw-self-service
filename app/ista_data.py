def recoverable_bundle_root(bundle: Path) -> Path:
    """Resolve a manifest-bound previous publication after an interrupted directory swap."""
    if bundle.exists():
        return bundle
    marker = bundle.parent / f".{bundle.name}.recovery.json"
    if marker.exists() or marker.is_symlink():
        try:
            if marker.is_symlink() or marker.stat().st_size > 4096:
                return bundle
            record = json.loads(marker.read_bytes())
            name = record.get("directory")
            digest = record.get("manifest_sha256")
            if (
                record.get("schema") != 1
                or not isinstance(name, str)
                or Path(name).name != name
                or "/" in name
                or "\\" in name
                or not name.startswith(f".{bundle.name}.previous-")
                or not isinstance(digest, str)
                or not re.fullmatch(r"[0-9a-f]{64}", digest)
            ):
                return bundle
            previous = bundle.parent / name
            manifest = previous / "manifest.json"
            if (
                previous.is_symlink()
                or manifest.is_symlink()
                or not previous.is_dir()
                or manifest.stat().st_size > 2 * 1024 * 1024
                or hashlib.sha256(manifest.read_bytes()).hexdigest() != digest
            ):
                return bundle
            return previous
        except (OSError, ValueError, AttributeError):
            return bundle
    # Compatibility for crashes from builders predating the explicit marker.
    candidates = list(bundle.parent.glob(f".{bundle.name}.previous-*"))
    if len(candidates) == 1 and candidates[0].is_dir() and not candidates[0].is_symlink():
        return candidates[0]
    return bundle


class IstaDataSource:
    """Job assets; runtime is bundle-only, explicit folder inputs are for builders."""

    def __init__(self, providers: Iterable[DataProvider]) -> None:
        """Use providers in lookup order."""
        self.providers: list[DataProvider] = list(providers)

    @classmethod
    def from_paths(cls, bundle: Path | None, folder: str | Path | None) -> "IstaDataSource":
        """Explicit builder/research inputs; app runtime passes no source folder."""
        providers: list[DataProvider] = []
        if bundle is not None:
            bundle = recoverable_bundle_root(bundle)
        if bundle is not None and (bundle / "manifest.json").is_file():
            try:
                providers.append(BundleProvider(bundle))
            except DataFormatError as exc:
                logger.warning("Bundled data ignored: %s", exc)
        if folder:
            check = validate_ista_folder(folder)
            if check.ok and check.root is not None and check.version_supported:
                providers.append(FolderProvider(check.root))
            elif check.ok:
                # D-60: only the 4.29 data release is supported.
                logger.warning("ISTA folder ignored: data version %r is not 4.29", check.version)
            else:
                logger.warning("ISTA folder ignored: %s", check.message)
        return cls(providers)

    @classmethod
    def from_settings(cls) -> "IstaDataSource":
        """Use generated assets only, ignoring obsolete source-folder settings."""
        return cls.from_paths(bundle_root(), None)

    def locate(self, name: str) -> tuple[Path, Path] | None:
        """Job file and the job directory it must be loaded with, or ``None``.

        Group files resolve variants and external tables from that directory, so a
        file and its directory always come from the same provider.
        """
        for provider in self.providers:
            try:
                path = provider.job_file(name)
            except (OSError, DataFormatError) as exc:
                logger.warning("%s: job data rejected: %s", provider.label, exc)
                continue
            if path is not None:
                return path, provider.ecu_dir
        return None

    def job_file(self, name: str) -> Path | None:
        """Job file by name or stem (``g_motor.grp``, ``DME_BX8``), case-insensitive."""
        found = self.locate(name)
        return found[0] if found else None

    def main_series(self, series: str) -> str | None:
        """KIS main series for a series or main series code (``F048`` -> ``F056``)."""
        code = normalize_series(series)
        if code in self.available_series():
            return code
        for provider in self.providers:
            main = provider.main_series(code)
            if main:
                return main
        return None

    def series_ecus(self, series: str) -> list[IstaEcu]:
        """Target ECU list for a series or main series; empty if no provider has it."""
        main = self.main_series(series)
        if main is None:
            return []
        for provider in self.providers:
            try:
                ecus = provider.series_ecus(main)
            except (OSError, DataFormatError) as exc:
                logger.warning("%s: ECU list %s unreadable: %s", provider.label, main, exc)
                continue
            if ecus is not None:
                return ecus
        return []

    def uds_variants(self) -> dict[str, str]:
        """Merge exact source identities in provider order, with bundle precedence."""
        result: dict[str, str] = {}
        for provider in self.providers:
            try:
                variants = provider.uds_variants()
            except (OSError, DataFormatError) as exc:
                logger.warning("%s: UDS identities unavailable: %s", provider.label, exc)
                continue
            for key, name in variants.items():
                result.setdefault(key, name)
        return result

    def available_series(self) -> list[str]:
        """KIS main series available from any provider."""
        return sorted({s for p in self.providers for s in p.available_series()})


def load_job_file(engine: Any, name: str, source: IstaDataSource | None = None) -> Path:
    """Load a job file into a ``JobEngine`` from the data source.

    Args:
        engine: ``app.ediabas.JobEngine``.
        name: Job file name or stem.
        source: Data source; defaults to ``IstaDataSource.from_settings()``.

    Returns:
        The loaded file's path.

    Raises:
        FileNotFoundError: No provider has the file.
        JobError: The engine refused the file.
    """
    found = (source or IstaDataSource.from_settings()).locate(name)
    if found is None:
        raise FileNotFoundError(f"Job file {name} is not available")
    path, ecu_dir = found
    engine.load(path, ecu_dir=ecu_dir)
    return path
