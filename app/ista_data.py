# Series map and version


def normalize_series(series: str) -> str:
    """Series code in the four-character form of the series map (``F48`` -> ``F048``)."""
    code = series.strip().upper()
    match = re.fullmatch(r"([A-Z])(\d{2})", code)
    return f"{match.group(1)}0{match.group(2)}" if match else code


def read_series_map(brref: Path) -> dict[str, str]:
    """Map each series (e.g. ``F048``) to its KIS main series (e.g. ``F056``)."""
    try:
        root = ET.parse(brref).getroot()
    except ET.ParseError as exc:
        raise DataFormatError("Series reference file is not valid XML") from exc
    mapping: dict[str, str] = {}
    for main in root.iter():
        if not main.tag.endswith("mainSeries"):
            continue
        name = (main.get("name") or "").strip().upper()
        if not _SERIES_PATTERN.match(name):
            continue
        for series in main:
            text = (series.text or "").strip().upper()
            if series.tag.endswith("series") and _SERIES_PATTERN.match(text):
                mapping[text] = name
    return mapping


def read_data_version(rheingold: Path) -> str:
    """Data version recorded in the folder's text databases (``RG_VERSION_*``), or ``""``.

    The smallest readable database is used; databases are opened read-only.
    """

    def size(path: Path) -> int:
        try:
            return path.stat().st_size
        except OSError:
            return -1

    candidates = [p for p in (rheingold / "SQLiteDBs").glob("*.sqlite") if size(p) >= 0]
    databases = sorted(candidates, key=size)
    for database in databases:
        try:
            connection = sqlite3.connect(f"{database.resolve().as_uri()}?mode=ro", uri=True)
        except sqlite3.Error:
            continue
        try:
            tables = [
                row[0]
                for row in connection.execute(
                    "SELECT name FROM sqlite_master WHERE type = 'table' AND name LIKE ?",
                    ("RG_VERSION%",),
                )
            ]
            for table in tables:
                if not re.fullmatch(r"RG_VERSION_[A-Z_]+", table):
                    continue
                row = connection.execute(f'SELECT * FROM "{table}" LIMIT 1').fetchone()
                if row and isinstance(row[0], str):
                    language = row[1] if len(row) > 1 and isinstance(row[1], str) else ""
                    return f"{row[0]} ({language})" if language else row[0]
        except sqlite3.Error:
            continue
        finally:
            connection.close()
    return ""


