# Providers


class DataProvider(Protocol):
    """A source of job files and model ECU lists."""

    label: str
    ecu_dir: Path

    def job_file(self, name: str) -> Path | None:
        """Job file by name or stem, case-insensitive."""
        ...

    def series_ecus(self, main_series: str) -> list[IstaEcu] | None:
        """ECU list of a KIS main series, or ``None`` if not provided."""
        ...

    def available_series(self) -> list[str]:
        """KIS main series this provider has ECU lists for."""
        ...

    def main_series(self, series: str) -> str | None:
        """KIS main series of a series code."""
        ...


class _JobIndex:
    """Case-insensitive index of a job file directory, built on first use."""

    def __init__(self, directory: Path) -> None:
        self._directory = directory
        self._files: dict[str, Path] | None = None

    def _names(self) -> dict[str, Path]:
        if self._files is None:
            files: dict[str, Path] = {}
            if self._directory.is_dir():
                for path in self._directory.iterdir():
                    if path.suffix.lower() in JOB_SUFFIXES and path.is_file():
                        files[path.name.lower()] = path
            self._files = files
        return self._files

    def find(self, name: str) -> Path | None:
        files = self._names()
        wanted = Path(name.strip()).name.lower()
        if not wanted:
            return None
        if Path(wanted).suffix in JOB_SUFFIXES:
            return files.get(wanted)
        # A bare stem must be unambiguous between PRG and GRP.
        matches = [files[f"{wanted}{s}"] for s in JOB_SUFFIXES if f"{wanted}{s}" in files]
        return matches[0] if len(matches) == 1 else None

    def counts(self) -> tuple[int, int]:
        names = self._names()
        return (
            sum(n.endswith(".prg") for n in names),
            sum(n.endswith(".grp") for n in names),
        )


class BundleProvider:
    """The compact bundle written by ``scripts/build_ista_bundle.py``."""

    def __init__(self, root: Path) -> None:
        """Open a bundle directory; raises ``DataFormatError`` if it is not one."""
        manifest_path = root / "manifest.json"
        try:
            manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        except (OSError, ValueError) as exc:
            raise DataFormatError("Bundle manifest is missing or unreadable") from exc
        if not isinstance(manifest, dict) or manifest.get("format") != BUNDLE_FORMAT:
            raise DataFormatError("Bundle manifest has an unsupported format")
        self.root = root
        self.manifest: dict[str, Any] = manifest
        self.ecu_dir = root / "ecu"
        self.label = "Bundled data"
        series_map = manifest.get("series_map", {})
        self._series_map = (
            {str(k): str(v) for k, v in series_map.items()} if isinstance(series_map, dict) else {}
        )
        main = manifest.get("main_series", {})
        self._main = sorted(str(k) for k in main) if isinstance(main, dict) else []
        self._index = _JobIndex(self.ecu_dir)

    @property
    def source_version(self) -> str:
        """Data version of the folder the bundle was built from."""
        source = self.manifest.get("source", {})
        return str(source.get("version", "")) if isinstance(source, dict) else ""

    def job_file(self, name: str) -> Path | None:
        """Job file by name or stem, case-insensitive."""
        return self._index.find(name)

    def series_ecus(self, main_series: str) -> list[IstaEcu] | None:
        """Bundled ECU list of a KIS main series."""
        if main_series not in self._main:
            return None
        path = self.root / "series" / f"{main_series}.json"
        try:
            content = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError) as exc:
            raise DataFormatError(f"Bundled ECU list {main_series} is unreadable") from exc
        items = content.get("ecus") if isinstance(content, dict) else None
        if not isinstance(items, list):
            raise DataFormatError(f"Bundled ECU list {main_series} has no ECU entries")
        return [_checked_ecu(item) for item in items]

    def available_series(self) -> list[str]:
        """Bundled KIS main series."""
        return list(self._main)

    def main_series(self, series: str) -> str | None:
        """KIS main series of a series code, from the bundled series map."""
        return self._series_map.get(series.upper())


class FolderProvider:
    """A user-selected ISTA 4.29 installation (its ``Rheingold`` directory)."""

    def __init__(self, rheingold: Path) -> None:
        """Use an already validated ``Rheingold`` directory."""
        self.root = rheingold
        self.ecu_dir = rheingold / "Ecu"
        self.label = "ISTA folder"
        self._kiswb = rheingold / "PSdZ" / "kiswb"
        self._brref = rheingold / "PSdZ" / "mapping" / "brref.xml"
        self._index = _JobIndex(self.ecu_dir)
        self._groups: dict[int, list[str]] | None = None
        self._series_map: dict[str, str] | None = None

    def job_file(self, name: str) -> Path | None:
        """Job file by name or stem, case-insensitive."""
        return self._index.find(name)

    def series_ecus(self, main_series: str) -> list[IstaEcu] | None:
        """ECU list read from ``PSdZ/kiswb/<main series>``."""
        if main_series not in self.available_series():
            return None
        return read_kis_ecus(self._kiswb / main_series, self._group_map())

    def available_series(self) -> list[str]:
        """KIS main series present in the folder."""
        if not self._kiswb.is_dir():
            return []
        return sorted(
            d.name
            for d in self._kiswb.iterdir()
            if _SERIES_PATTERN.match(d.name) and (d / "KIS.script").is_file()
        )

    def main_series(self, series: str) -> str | None:
        """KIS main series of a series code, from ``brref.xml``."""
        if self._series_map is None:
            try:
                self._series_map = read_series_map(self._brref)
            except (OSError, DataFormatError) as exc:
                logger.warning("Series map unavailable: %s", exc)
                self._series_map = {}
        return self._series_map.get(series.upper())

    def _group_map(self) -> dict[int, list[str]]:
        if self._groups is None:
            table = self.job_file(GROUP_TABLE_FILE)
            try:
                self._groups = groups_by_address(read_group_assignments(table)) if table else {}
            except (OSError, DataFormatError) as exc:
                logger.warning("Group assignment table unavailable: %s", exc)
                self._groups = {}
        return self._groups


def _checked_ecu(item: Any) -> IstaEcu:
    if not isinstance(item, dict):
        raise DataFormatError("Bundled ECU entry is not an object")
    name, address = item.get("name"), item.get("address")
    if not isinstance(name, str) or not isinstance(address, int) or not 0 <= address <= 0xFF:
        raise DataFormatError("Bundled ECU entry has an invalid name or address")
    groups = item.get("groups", [])
    return IstaEcu(
        name=name,
        address=address,
        description=str(item.get("description", "")),
        gateway=bool(item.get("gateway", False)),
        groups=[str(g) for g in groups] if isinstance(groups, list) else [],
    )


# ---------------------------------------------------------------------------
# Folder validation and settings


def rheingold_dir(path: Path) -> Path:
    """Accept the installation root or its ``Rheingold`` directory."""
    return path / "Rheingold" if (path / "Rheingold").is_dir() else path


def validate_ista_folder(path: str | Path) -> FolderCheck:
    """Check that a folder is a usable ISTA installation.

    Requires ``Rheingold/Ecu`` with PRG and GRP files, ``t_grtb.prg`` and at least one
    ``PSdZ/kiswb/<series>`` ECU list. The data version is recorded when present.
    """
    root = rheingold_dir(Path(path).expanduser())
    if not (root / "Ecu").is_dir():
        return FolderCheck(False, "No Ecu folder was found in the selected folder.")
    index = _JobIndex(root / "Ecu")
    prg_count, grp_count = index.counts()
    if prg_count == 0 or grp_count == 0:
        return FolderCheck(False, "The Ecu folder contains no PRG/GRP job files.", root)
    if index.find(GROUP_TABLE_FILE) is None:
        return FolderCheck(False, "The Ecu folder has no group assignment table.", root)
    series = FolderProvider(root).available_series()
    if not series:
        return FolderCheck(False, "No PSdZ/kiswb ECU lists were found.", root)
    version = read_data_version(root)
    message = f"{prg_count} PRG and {grp_count} GRP files, {len(series)} model ECU lists"
    return FolderCheck(True, message, root, version, prg_count, grp_count, series)


def saved_ista_folder() -> str:
    """The ISTA folder saved in the application settings, or ``""``."""
    from PySide6.QtCore import QSettings

    value = QSettings().value(SETTINGS_KEY, "")
    return value if isinstance(value, str) else ""


def save_ista_folder(path: str) -> None:
    """Persist the ISTA folder (``""`` clears it)."""
    from PySide6.QtCore import QSettings

    settings = QSettings()
    if path:
        settings.setValue(SETTINGS_KEY, path)
    else:
        settings.remove(SETTINGS_KEY)


def bundle_root() -> Path:
    """Location of the bundled data in a checkout or packaged app."""
    return resource_path(BUNDLE_DIRNAME)


